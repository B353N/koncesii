import { describe, expect, test } from "vitest";
import {
  documentRank,
  extractDocAmounts,
  extractDocFacts,
  normalizeDocText,
  parseDocNumber,
  splitPages,
} from "./documentFacts";

const one = (text: string) => extractDocFacts([text]);

describe("parseDocNumber", () => {
  test.each([
    ["2 300,81", 2300.81],
    ["1.500,00", 1500],
    ["1.500", 1500],
    ["1,500.00", 1500],
    ["2300.81", 2300.81],
    ["2.50", 2.5],
    ["15000", 15000],
    ["685,13", 685.13],
  ])("%s → %d", (raw, v) => expect(parseDocNumber(raw)).toBe(v));
});

describe("normalizeDocText / splitPages", () => {
  test("слепва пренесените думи и нормализира интервалите", () => {
    expect(
      normalizeDocText("годишно концеси-\nонно  възна-\n граждение\n\nот"),
    ).toBe("годишно концесионно възнаграждение от");
  });
  test("form feed разделя страниците; празната опашка не е страница", () => {
    expect(splitPages("а\fб\f")).toEqual(["а", "б"]);
    expect(splitPages("само една")).toEqual(["само една"]);
  });
});

describe("extractDocFacts", () => {
  test("срок в години, със словом в скоби", () => {
    const [f] = one(
      "Чл. 3. Концесията се предоставя за срок от 25 (двадесет и пет) години, считано от датата на влизане в сила.",
    );
    expect(f).toMatchObject({
      field: "term",
      months: 300,
      valueRaw: "25 (двадесет и пет) години",
      priority: 1,
      page: 1,
    });
    expect(f!.quote).toContain("срок от 25 (двадесет и пет) години");
  });

  test("срок в месеци", () => {
    expect(one("Срокът на концесията е 420 месеца.")[0]).toMatchObject({
      field: "term",
      months: 420,
    });
  });

  test("законов максимум и удължаване не са срокът", () => {
    expect(
      one("Срокът на концесията не може да бъде по-дълъг от 35 години."),
    ).toEqual([]);
    expect(one("Срокът на концесията може да се удължава с 5 години.")).toEqual(
      [],
    );
    expect(one("Срокът на концесията е до 35 години.")).toEqual([]);
  });

  test("годишно възнаграждение с разделител на хилядите и словом", () => {
    const facts = one(
      "Годишното концесионно възнаграждение е в размер на 2 300,81 лв. (две хиляди и триста лева и 81 ст.) без ДДС.",
    );
    expect(facts).toHaveLength(1);
    expect(facts[0]).toMatchObject({
      field: "annual_payment",
      amount: 2300.81,
      currency: "BGN",
      eur: 1176.39,
      valueRaw: "2 300,81 лв.",
    });
  });

  test("общата котва изисква „годишно“ около сумата", () => {
    expect(
      one(
        "Концесионерът заплаща концесионно възнаграждение в размер на 4 500 лева годишно.",
      )[0],
    ).toMatchObject({ field: "annual_payment", amount: 4500 });
    expect(
      one(
        "Концесионерът заплаща концесионно възнаграждение в размер на 4 500 лева по банков път.",
      ),
    ).toEqual([]);
  });

  test("еднократното не пълни годишното", () => {
    const facts = one(
      "Еднократното концесионно възнаграждение е 10 000 евро и се плаща при подписване.",
    );
    expect(facts.map((f) => f.field)).toEqual(["onetime_payment"]);
    expect(facts[0]).toMatchObject({ currency: "EUR", eur: 10000 });
  });

  test("процент от приходите → payment_percent, не сума", () => {
    const facts = one(
      "Годишното концесионно възнаграждение е 4 % (четири на сто) от нетните приходи от продажби, но не по-малко от 3 000 лв.",
    );
    expect(facts).toHaveLength(1);
    expect(facts[0]).toMatchObject({ field: "payment_percent", percent: 4 });
  });

  test("стойност на концесията в хиляди лева", () => {
    expect(
      one("Прогнозната стойност на концесията е 1 250 хил. лв. без ДДС.")[0],
    ).toMatchObject({ field: "value", amount: 1_250_000, currency: "BGN" });
  });

  test("първоначалната прогнозна стойност от обявлението не е стойността", () => {
    const values = one(
      "V.2.4) Информация относно стойността на концесията и основните финансови условия (без да се включва ДДС) Първоначална прогнозна обща стойност на поръчката/обособената позиция/концесията: 3 898 229 907.50 EUR Обща стойност на концесията/обособената позиция: 4 394 069 000.00 EUR",
    ).filter((f) => f.field === "value");
    expect(values.map((f) => f.amount)).toEqual([4_394_069_000]);
  });

  test("споменаването на срока не е срокът", () => {
    for (const text of [
      "Гаранцията се предоставя в срок до 18 месеца преди изтичане срока на концесията. ие със срок на валидност 6 месеца след това.",
      "Концесионерът се задължава по време на целия срок на концесията да представя документите не по-късно от 1 месец от издаването им.",
      "За първите 10 (десет) години от срока на концесията - инвестиции в размер на 200 000 лева.",
    ]) {
      expect(one(text).filter((f) => f.field === "term")).toEqual([]);
    }
    expect(
      one("Срокът на концесията е 35 (тридесет и пет) години.")[0],
    ).toMatchObject({ field: "term", months: 420 });
    expect(
      one(
        "Плащането е дължимо след изтичане на гратисния период от 3 (три) години от влизане в сила на договора.",
      )[0],
    ).toMatchObject({ field: "grace_period", months: 36 });
  });

  test("„26 години и 6 месеца“ е 318 месеца", () => {
    expect(
      one("Договорът се сключва за срок от 26 години и 6 (шест) месеца.")[0],
    ).toMatchObject({
      field: "term",
      months: 318,
      valueRaw: "26 години и 6 (шест) месеца",
    });
  });

  test("минимумът от офертата, досегашният срок и увеличението не са стойността", () => {
    expect(
      one(
        "1.1.Размер на годишно концесионното възнаграждение - минимум 3120 (три хиляди сто и двадесет) лева",
      ).filter((f) => f.field === "annual_payment"),
    ).toEqual([]);
    expect(
      one(
        "Срок на концесията: Досегашен срок: [240] месеца Нов срок: [320] месеца",
      ).filter((f) => f.field === "term"),
    ).toEqual([]);
    expect(
      one(
        "считано от 01.01.2025 г. годишното концесионно възнаграждение се увеличава с 5 323,57 EUR",
      ).filter((f) => f.field === "annual_payment"),
    ).toEqual([]);
  });

  test("гаранции, минимални цени и цени на единица не са възнаграждението", () => {
    expect(
      one(
        "Годишното концесионно възнаграждение се обезпечава с гаранция от 1 000 лв.",
      ),
    ).toEqual([]);
    expect(
      one("Минималното годишно концесионно възнаграждение е 800 лв."),
    ).toEqual([]);
    expect(
      one("Годишното концесионно възнаграждение е 0,12 лв./кв.м площ."),
    ).toEqual([]);
  });

  test("прозорецът спира при следващата клауза", () => {
    expect(
      one(
        "Годишното концесионно възнаграждение се заплаща до 31 март. Чл. 8. Концесионерът внася 2 000 лв. такса.",
      ),
    ).toEqual([]);
  });

  test("гратисен период", () => {
    expect(
      one("Гратисният период е 2 (две) години от сключване на договора.")[0],
    ).toMatchObject({ field: "grace_period", months: 24 });
  });

  // Случаи от първото реално пускане (25.09.2026) върху документите на НКР
  test("„127 114.36 лв.“ е една сума, не 114.36", () => {
    expect(
      one(
        "Стойност на концесията – 127 114.36 лв. (сто двадесет и седем хиляди) без ДДС.",
      )[0],
    ).toMatchObject({ field: "value", amount: 127114.36 });
  });

  test("грешно групирано „1312 500 лв.“ не дава 500 лв.", () => {
    expect(
      one(
        "Прогнозната стойност на концесията е 1312 500 лв. /един милион/.",
      ).filter((f) => f.field === "value"),
    ).toEqual([]);
  });

  test("„[360] месеца“ от формуляра; удължаването след него не е срокът", () => {
    const facts = one(
      "1) Срок на концесията, без предвидените удължавания: [360] месеца 2) Предвидени удължавания: Да. Срока може да бъде продължен с 10 години.",
    );
    expect(facts.filter((f) => f.field === "term")).toMatchObject([
      { months: 360 },
    ]);
  });

  test("„удължава срокът на концесията … който е 20 години“ не е срокът", () => {
    expect(
      one(
        "Общинският съвет удължава срокът на концесията с една трета от срока, определен с концесионния договор, който е 20 години.",
      ),
    ).toEqual([]);
  });

  test("ДДС след сумата се отбелязва", () => {
    expect(
      one(
        "Концесионерът заплаща еднократно концесионно възнаграждение в размер на 1 700 лв. (хиляда и седемстотин лева) с ДДС, дължимо преди подписване.",
      )[0],
    ).toMatchObject({ field: "onetime_payment", amount: 1700, vat: "with" });
    expect(
      one(
        "Годишно концесионно възнаграждение в размер на 1600 (хиляда и шестстотин) лева без ДДС, съответно 1920 лева с ДДС.",
      )[0],
    ).toMatchObject({ amount: 1600, vat: "without" });
  });

  test("цитатът е изречението с котвата, не опашката на предното", () => {
    const [f] = one(
      "(3) Концесионерът внася гаранция в размер на 1 000 лв. Чл. 6. Гратисният период е 2 (две) години от сключване на договора. Чл. 7. Друго.",
    );
    expect(f!.quote).toBe(
      "Гратисният период е 2 (две) години от сключване на договора.",
    );
  });

  test("страниците се номерират от 1 и фактите се подреждат по страница", () => {
    const facts = extractDocFacts([
      "Увод без стойности.",
      "Срокът на концесията е 30 години.",
    ]);
    expect(facts[0]).toMatchObject({ page: 2, months: 360 });
  });

  test("детерминистично: същият текст дава същото извличане", () => {
    const t = [
      "Концесията се предоставя за срок от 35 години. Годишното концесионно възнаграждение е 1 500 лв.",
    ];
    expect(extractDocFacts(t)).toEqual(extractDocFacts(t));
  });
});

describe("extractDocAmounts", () => {
  test("всички суми с контекст и страница", () => {
    const amounts = extractDocAmounts([
      "Гаранция 1 000 лв. и такса 50 евро.",
      "Общо: 2 300,81 лв.",
    ]);
    expect(amounts.map((a) => [a.page, a.amount, a.currency])).toEqual([
      [1, 1000, "BGN"],
      [1, 50, "EUR"],
      [2, 2300.81, "BGN"],
    ]);
    expect(amounts[0]!.context).toContain("Гаранция 1 000 лв.");
  });

  test("номера на членове и дати не са суми", () => {
    expect(extractDocAmounts(["Чл. 12, ал. 3 от 01.02.2020 г."])).toEqual([]);
  });
});

test("documentRank: договорът е меродавен, анексите — последни", () => {
  expect(documentRank("Концесионен договор (PDF)")).toBe(0);
  expect(documentRank("Решение № 714")).toBe(2);
  expect(documentRank("Анекс 1 към договора")).toBe(3);
  expect(documentRank(null)).toBe(1);
});

test("documentRank: при линк „Свали“ решава името на файла", () => {
  expect(documentRank("Свали", "dogovor O-001131.pdf")).toBe(0);
  expect(documentRank("Свали", "Concession Agreement Sofia Airport.pdf")).toBe(
    0,
  );
  expect(documentRank("Свали", "Reshenie_PK 5_17.07.2019.pdf")).toBe(2);
  expect(documentRank("Свали", "Aneks 2 kym dogovor.pdf")).toBe(3);
  // отчетът и проектът споменават договора, но не са договорът
  expect(
    documentRank(
      "Свали",
      "Информация за изпълнение на концесионен договор 2023 г.pdf",
    ),
  ).toBe(2);
  expect(documentRank("Свали", "Приложение №20 - Проект на договор.doc")).toBe(
    2,
  );
  expect(documentRank("Свали", "notice_bg.pdf")).toBe(1);
  // смисленото заглавие печели пред името на файла
  expect(documentRank("Решение № 714", "dogovor.pdf")).toBe(2);
});
