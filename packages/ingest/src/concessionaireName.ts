import { normText } from "./text";

/**
 * Името на концесионера в регистрите идва слято с идентификатора му:
 * „"МАРИЯ-М-65" ЕООД с БУЛСТАТ 201207954", „„Гьошев ИН" ЕООД, ЕИК
 * 202273601", „ЕТ „АПОЛО - Йордан Йорданов" с ЕИК 123456789". ЕИК-ът се
 * съхранява в собствена колона и се показва отделно, затова от името се
 * маха - заедно със свързващата дума („с", „със"), която иначе остава
 * като увиснало „ЕООД с".
 *
 * Това не е поправка на регистрова стойност: суровият низ остава в
 * staging таблиците (raw_egov_rows, raw_nkr_*), а ЕИК-ът - в своята
 * колона. Тук се маха само дублирането в полето за име.
 */

/** „, ЕИК 123456789", „ с БУЛСТАТ 201207954", „ (ЕИК: 1234567890123)" */
const IDENTIFIER_RE =
  /[,;(]?\s*(?:с(?:ъс)?\s+)?(?:еик|булстат)\s*(?:номер|№)?[\s:.№#-]*\d{9,13}\)?/giu;

/** Увиснало свързващо „с"/„със" в края, ако идентификаторът е отпаднал. */
const DANGLING_RE = /[\s,;(-]+с(?:ъс)?\s*$/iu;

/** Празни остатъци: пунктуация и интервали в края. */
const TRAILING_RE = /[,;(\s-]+$/u;

export function cleanConcessionaireName(input: unknown): string {
  return normText(input)
    .replace(IDENTIFIER_RE, "")
    .replace(DANGLING_RE, "")
    .replace(TRAILING_RE, "")
    .trim();
}
